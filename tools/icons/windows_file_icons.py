"""The Material file icons for the Windows app (docs/adr/0011-material-file-icons.md),
from the Mac's (apps/macos/shared/icons/Resources/FileIcons, made by
build_file_icons.py), so both apps show the same drawings for the same names:

    python3 -I tools/icons/windows_file_icons.py           # PNGs and the table
    python3 -I tools/icons/windows_file_icons.py --check   # the table matches map.json

writes each PDF as 32 and 64 pixel PNGs (pdf_to_png.swift, this Mac's
AppKit) to apps/windows/shared/icons/FileIcons, and map.json as the Zig
tables of apps/windows/shared/icons/file_icons.zig (sorted, for binary
search). Run it again after build_file_icons.py.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MAC = ROOT / "apps/macos/shared/icons/Resources/FileIcons"
OUT = ROOT / "apps/windows/shared/icons/FileIcons"
TABLE = ROOT / "apps/windows/shared/icons/file_icons.zig"
SIZES = (32, 64)


def table():
    data = json.loads((MAC / "map.json").read_text())
    icons = sorted(p.stem for p in MAC.glob("*.pdf"))
    index = {name: i for i, name in enumerate(icons)}
    lines = [
        "//! Generated by tools/icons/windows_file_icons.py from the Mac's",
        "//! FileIcons/map.json: do not edit. The Material Icon Theme's drawings",
        "//! (docs/adr/0011-material-file-icons.md) as PNGs, and which names and",
        "//! extensions show them, sorted for binary search.",
        "",
        "pub const Entry = struct { []const u8, u8 };",
        "",
        "pub const names = [_][]const u8{",
    ]
    lines += [f'    "{n}",' for n in icons]
    lines.append("};")
    for size in SIZES:
        lines += ["", f"pub const png{size} = [_][]const u8{{"]
        lines += [f'    @embedFile("FileIcons/{n}-{size}.png"),' for n in icons]
        lines.append("};")
    for key in ("extensions", "names", "folders"):
        field = "file_names" if key == "names" else key
        lines += ["", f"pub const {field} = [_]Entry{{"]
        for k in sorted(data[key]):
            icon = data[key][k]
            if icon in index:
                lines.append(f'    .{{ "{k}", {index[icon]} }},')
        lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    expected = table()
    if "--check" in sys.argv:
        if not TABLE.exists() or TABLE.read_text() != expected:
            print("file_icons.zig fora de sincronia com map.json: rode tools/icons/windows_file_icons.py")
            return 1
        return 0
    for old in OUT.glob("*.png"):
        old.unlink()
    subprocess.run(["swift", str(Path(__file__).parent / "pdf_to_png.swift"), str(MAC), str(OUT)] + [str(s) for s in SIZES], check=True)
    TABLE.write_text(expected)
    print(f"{TABLE.relative_to(ROOT)}: {expected.count('@embedFile')} PNGs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
