"""Writes the Windows app's Phosphor code points from the Mac's list, so the
icons have one source (apps/macos/shared/icons/Icon.swift, ADR 0008):

    python3 -I tools/icons/windows_icons.py          writes the Zig file
    python3 -I tools/icons/windows_icons.py --check  fails if it is stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SOURCE = ROOT / "apps/macos/shared/icons/Icon.swift"
TARGET = ROOT / "apps/windows/shared/icons/phosphor.zig"


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def render():
    cases = re.findall(r"case (\w+) = (0x[0-9A-Fa-f]+)", SOURCE.read_text())
    lines = [
        "//! Phosphor code points (regular weight), generated by",
        "//! tools/icons/windows_icons.py from apps/macos/shared/icons/Icon.swift.",
        "//! Add an icon there and run the script; do not edit this file.",
        "",
    ]
    lines += [f"pub const {snake(n)}: u21 = {v};" for n, v in cases]
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != text:
            print(f"{TARGET.relative_to(ROOT)} desatualizado: rode python3 -I tools/icons/windows_icons.py")
            return 1
        return 0
    TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
