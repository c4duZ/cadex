#!/usr/bin/env python3
"""Generates the app's design tokens from docs/design/work-frame/tokens.json
(docs/adr/0035-work-frame.md, plan 25 phase C), so no value of the mockups
is typed by hand in Swift:

- apps/macos/shared/looks/DesignTokens.swift: the primitives (colors, font
  sizes and weights, line heights, tracking, radii, strokes, opacity,
  shadows, the spacing scale);
- apps/macos/shared/looks/DesignTokens<Region>.swift: the measures of each
  piece (`components`), pointing at the primitives by name, one file per
  region of the frame (PARTS), each under the 500-line rule;
- apps/macos/features/themes/CadexNight.swift: the Cadex Night theme (the
  interface colors of `components.theme`, the terminal of
  `components.terminalTheme`).

`--check` (in make manifests) fails when the generated files differ from
what tokens.json gives. Run without it to write them.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TOKENS = ROOT / "docs/design/work-frame/tokens.json"
OUT_PRIMITIVES = ROOT / "apps/macos/shared/looks/DesignTokens.swift"
LOOKS = ROOT / "apps/macos/shared/looks"
# Which file each piece goes in; every component of tokens.json must be in one.
PARTS = {
    "Chrome": ["window", "titleBar", "search", "breadcrumb", "tab", "titleIconButton", "badge", "statusBar",
               "stateGlyph", "button"],
    "Columns": ["sidebar", "inspector"],
    "Center": ["pane", "preview", "popover", "sheet", "newTask"],
    "Pages": ["board", "race", "project", "home", "drawer"],
}
OUT_THEME = ROOT / "apps/macos/features/themes/CadexNight.swift"
HEADER = ("// Generated by tools/design/build_tokens.py from docs/design/work-frame/tokens.json\n"
          "// (docs/adr/0035-work-frame.md). Do not edit: change the mockup and tokens.json, then run it.\n")
GROUPS = ["color", "fontSize", "fontWeight", "lineHeight", "tracking", "radius", "stroke", "opacity", "shadow"]
SWIFT_GROUP = {"color": "Color", "fontSize": "FontSize", "fontWeight": "FontWeight", "lineHeight": "LineHeight",
               "tracking": "Tracking", "radius": "Radius", "stroke": "Stroke", "opacity": "Opacity", "shadow": "Shadow"}
# The mockups' CSS weights as AppKit's. 650 has no named weight: it sits between semibold
# (0.3) and bold (0.4), the "unread" names of the tree (screens.md, Sidebar).
WEIGHTS = {400: ".regular", 500: ".medium", 600: ".semibold", 650: "NSFont.Weight(rawValue: 0.35)", 700: ".bold", 800: ".heavy"}


def ident(name):
    """"bg.window" → bgWindow, "shadow.40" → shadow40, "showAbovePercent" stays."""
    parts = re.split(r"[.\-_ ]", name)
    first, rest = parts[0], parts[1:]
    out = first[:1].lower() + first[1:] + "".join(p[:1].upper() + p[1:] for p in rest)
    return out if not out[:1].isdigit() else "n" + out


def number(v):
    return repr(float(v)).rstrip("0").rstrip(".") if float(v) != int(float(v)) else str(int(float(v)))


def color_expr(value):
    if value.startswith("#"):
        h = value[1:]
        return f"DesignTokens.rgb(0x{h.upper()})"
    r, g, b, a = [x.strip() for x in value[value.index("(") + 1:-1].split(",")]
    return f"DesignTokens.rgb(0x{int(r):02X}{int(g):02X}{int(b):02X}, alpha: {a})"


def shadow_layers(value, colors):
    layers = []
    for layer in value.split(","):
        bits = layer.split()
        inset = bits[0] == "inset"
        if inset:
            bits = bits[1:]
        nums = [b for b in bits if not b.startswith("{")]
        ref = next(b for b in bits if b.startswith("{"))[1:-1]
        x, y, blur = (float(n.replace("px", "")) for n in nums[:3])
        spread = float(nums[3].replace("px", "")) if len(nums) > 3 else 0
        layers.append(f".init(x: {number(x)}, y: {number(y)}, blur: {number(blur)}, spread: {number(spread)}, "
                      f"color: Color.{ident(ref)}, inset: {str(inset).lower()})")
    return layers


def primitives(t):
    out = [HEADER, "import AppKit\n",
           "/// The values of the new frame's mockups, by name (docs/design/work-frame/tokens.json).",
           "/// Sizes are design points: views scale them with UILooks (pt, rowHeight, font).",
           "public enum DesignTokens {",
           "    /// A color as 0xRRGGBB and an alpha, in sRGB.",
           "    public static func rgb(_ value: UInt32, alpha: CGFloat = 1) -> NSColor {",
           "        NSColor(srgbRed: CGFloat((value >> 16) & 0xFF) / 255, green: CGFloat((value >> 8) & 0xFF) / 255,",
           "                blue: CGFloat(value & 0xFF) / 255, alpha: alpha)",
           "    }\n",
           "    /// One layer of a shadow, as the mockups' CSS writes it: `y` grows downward and `inset`",
           "    /// draws inside the edge. AppKit's and a layer's shadowOffset grow upward: use `offset`.",
           "    public struct ShadowLayer: Sendable {",
           "        public let x: CGFloat, y: CGFloat, blur: CGFloat, spread: CGFloat",
           "        public let colorValue: @Sendable () -> NSColor",
           "        public let inset: Bool",
           "        public var color: NSColor { colorValue() }",
           "        /// For CALayer.shadowOffset and NSShadow in an unflipped view: y turned upward.",
           "        public var offset: CGSize { CGSize(width: x, height: -y) }",
           "        /// CSS blur is the shadow's whole spread; a layer's shadowRadius is about half of it.",
           "        public var layerRadius: CGFloat { blur / 2 }",
           "        init(x: CGFloat, y: CGFloat, blur: CGFloat, spread: CGFloat, color: @autoclosure @escaping @Sendable () -> NSColor, inset: Bool) {",
           "            self.x = x; self.y = y; self.blur = blur; self.spread = spread; self.colorValue = color; self.inset = inset",
           "        }",
           "    }\n"]
    out.append("    public enum Color {")
    for k, v in t["color"].items():
        out.append(f"        /// {k}: {v}")
        out.append(f"        public static var {ident(k)}: NSColor {{ {color_expr(v)} }}")
    out.append("    }\n")
    for group, typ in (("fontSize", "CGFloat"), ("lineHeight", "CGFloat"), ("stroke", "CGFloat"), ("opacity", "CGFloat")):
        out.append(f"    public enum {SWIFT_GROUP[group]} {{")
        for k, v in t[group].items():
            out.append(f"        public static let {ident(k)}: {typ} = {number(v)}")
        out.append("    }\n")
    out.append("    public enum FontWeight {")
    for k, v in t["fontWeight"].items():
        if int(v) not in WEIGHTS:
            sys.exit(f"tokens.json: fontWeight.{k} = {v} não tem peso do AppKit em WEIGHTS de build_tokens.py")
        out.append(f"        public static var {ident(k)}: NSFont.Weight {{ {WEIGHTS[int(v)]} }}")
    out.append("    }\n")
    out.append("    /// Letter spacing, in em: multiply by the font size for the kern.")
    out.append("    public enum Tracking {")
    for k, v in t["tracking"].items():
        out.append(f"        public static let {ident(k)}: CGFloat = {number(v.replace('em', '') or 0)}")
    out.append("    }\n")
    out.append("    public enum Radius {")
    for k, v in t["radius"].items():
        if str(v).endswith("%"):
            out.append(f"        /// {v}: a circle or a pill, half the shorter side.")
            out.append(f"        public static func {ident(k)}(_ side: CGFloat) -> CGFloat {{ side / 2 }}")
        else:
            out.append(f"        public static let {ident(k)}: CGFloat = {number(v)}")
    out.append("    }\n")
    out.append("    public enum Shadow {")
    for k, v in t["shadow"].items():
        layers = shadow_layers(v, t["color"])
        out.append(f"        /// {v}")
        out.append(f"        public static var {ident(k)}: [ShadowLayer] {{ [{', '.join(layers)}] }}")
    out.append("    }\n")
    out.append("    /// The spacing scale: every gap, padding and margin of the mockups.")
    out.append("    public static let space: [CGFloat] = [" + ", ".join(number(v) for v in t["space"]) + "]")
    out.append("}")
    return "\n".join(out).replace("Color.", "DesignTokens.Color.").replace("DesignTokens.DesignTokens.", "DesignTokens.") + "\n"


def resolve(key, value, t):
    """A component value that names a primitive: (swift type, expression)."""
    hits = [g for g in GROUPS if value in t[g]]
    if len(hits) > 1:
        hint = key.lower()
        prefer = [g for g in hits if g.lower() in hint or (g == "radius" and "radius" in hint)
                  or (g == "shadow" and "shadow" in hint) or (g == "fontWeight" and hint in ("weight", "name", "title"))]
        hits = prefer or hits
    g = hits[0]
    v = t[g][value]
    if g == "color":
        return "NSColor", f"DesignTokens.Color.{ident(value)}", True
    if g == "fontWeight":
        return "NSFont.Weight", f"DesignTokens.FontWeight.{ident(value)}", True
    if g == "shadow":
        return "[DesignTokens.ShadowLayer]", f"DesignTokens.Shadow.{ident(value)}", True
    if g == "radius" and str(v).endswith("%"):
        return "String", f'"{value}"', False
    return "CGFloat", f"DesignTokens.{SWIFT_GROUP[g]}.{ident(value)}", False


def insets(text):
    n = [float(x) for x in text.split()]
    top, right, bottom, left = (n * 4)[:4] if len(n) == 1 else (n[0], n[1], n[0], n[1]) if len(n) == 2 \
        else (n[0], n[1], n[2], n[1]) if len(n) == 3 else n
    return f"NSEdgeInsets(top: {number(top)}, left: {number(left)}, bottom: {number(bottom)}, right: {number(right)})"


def part(name, node, t, depth):
    pad = "    " * depth
    access = "" if depth == 1 else "public "
    out = [f"{pad}{access}enum {name[:1].upper() + name[1:]} {{"]
    for k, v in node.items():
        if k == "about":
            continue
        key = ident(k)
        if isinstance(v, dict):
            out += part(key, v, t, depth + 1)
        elif isinstance(v, bool):
            out.append(f"{pad}    public static let {key} = {str(v).lower()}")
        elif isinstance(v, (int, float)):
            out.append(f"{pad}    public static let {key}: CGFloat = {number(v)}")
        elif isinstance(v, list) and all(isinstance(x, (int, float)) for x in v):
            out.append(f"{pad}    public static let {key}: [CGFloat] = [{', '.join(number(x) for x in v)}]")
        elif isinstance(v, list):
            exprs = [resolve(k, x, t) for x in v]
            out.append(f"{pad}    public static var {key}: [{exprs[0][0]}] {{ [{', '.join(e[1] for e in exprs)}] }}")
        elif re.fullmatch(r"[\d. ]+", v):
            out.append(f"{pad}    public static let {key} = {insets(v)}")
        elif any(v in t[g] for g in GROUPS):
            typ, expr, computed = resolve(k, v, t)
            out.append(f"{pad}    public static {'var' if computed else 'let'} {key}: {typ}{' { ' + expr + ' }' if computed else ' = ' + expr}")
        else:
            out.append(f"{pad}    public static let {key} = \"{v}\"")
    out.append(f"{pad}}}")
    return out


def parts(t, names, region):
    out = [HEADER, "import AppKit\n",
           f"/// The measures of the {region.lower()} pieces of the new frame (tokens.json, `components`), in",
           "/// design points; what they name comes from `DesignTokens`. Padding is top, left, bottom, right.",
           "public extension DesignTokens {"]
    for name in names:
        out += part(name, t["components"][name], t, 1)
    out.append("}")
    return "\n".join(out) + "\n"


def theme(t):
    c, th, term = t["color"], t["components"]["theme"], t["components"]["terminalTheme"]

    def hx(name):
        v = c[name]
        assert v.startswith("#"), f"{name} must be opaque for the theme"
        return "RGB(0x" + v[1:].upper() + ")"
    ansi = ", ".join("0x" + c[n][1:].upper() for n in term["ansi"])
    return (HEADER + "import Strings\n\n"
            "/// Cadex Night, the theme of the new frame (docs/adr/0035-work-frame.md): the interface colors\n"
            "/// every theme has, and the terminal tuned to the mockups (plan 28 measures and tunes it).\n"
            "public extension Theme {\n"
            "    static let cadexNight = Theme(\n"
            "        name: \"Cadex Night\", dark: true,\n"
            "        interface: Interface(\n"
            f"            chrome: {hx(th['chrome'])}, panel: {hx(th['panel'])}, panelBorder: {hx(th['panelBorder'])},\n"
            f"            tabActive: {hx(th['tabActive'])}, field: {hx(th['field'])}, text: {hx(th['text'])},\n"
            f"            secondaryText: {hx(th['secondaryText'])}, accent: {hx(th['accent'])}),\n"
            "        terminal: Terminal(\n"
            f"            background: {hx(term['background'])}, foreground: {hx(term['foreground'])}, cursor: {hx(term['cursor'])},\n"
            f"            selection: {hx(term['selection'])},\n"
            f"            ansi: [{ansi}].map(RGB.init)))\n"
            "}\n")


def main():
    t = json.loads(TOKENS.read_text())
    placed = [n for names in PARTS.values() for n in names] + ["theme", "terminalTheme"]
    missing = [n for n in t["components"] if n not in placed]
    if missing:
        print("componentes sem arquivo em PARTS: " + ", ".join(missing))
        sys.exit(1)
    files = {OUT_PRIMITIVES: primitives(t), OUT_THEME: theme(t)}
    files.update({LOOKS / f"DesignTokens{region}.swift": parts(t, names, region) for region, names in PARTS.items()})
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in files.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("gerados fora do tokens.json (rode tools/design/build_tokens.py): " + ", ".join(stale))
            sys.exit(1)
        return
    for p, text in files.items():
        p.write_text(text)
        print(f"{p.relative_to(ROOT)}: {text.count(chr(10))} linhas")


if __name__ == "__main__":
    main()
