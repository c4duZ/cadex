#!/usr/bin/env python3
"""The Documentação screen's guides (plan 40 G), from upstream's own catalog.

Reads, in the cargo checkout of the pinned ai-memory commit (the `rev` in
core/features/memory/server/Cargo.toml), ai-memory-web's `DOCUMENTS` (id,
title, description, category, the Markdown's path and its pt-BR one) and the
Portuguese of each title, description and category from ai-memory-core's
diagnostics.ftl (the `i18n.label` its docs page shows them through), and
writes apps/macos/features/memory/panel/PanelGuides.swift. Run it after an
upstream update: `python3 tools/memory_panel_guides.py`.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CARGO = ROOT / "core/features/memory/server/Cargo.toml"
OUT = ROOT / "apps/macos/features/memory/panel/PanelGuides.swift"
REPO = "https://github.com/akitaonrails/ai-memory"


def pinned_rev() -> str:
    match = re.search(r'ai-memory-core = \{ git = "[^"]+", rev = "([0-9a-f]+)"', CARGO.read_text())
    if not match:
        sys.exit("no ai-memory-core rev in Cargo.toml")
    return match.group(1)


def checkout(rev: str) -> pathlib.Path:
    for path in (pathlib.Path.home() / ".cargo/git/checkouts").glob(f"ai-memory-*/{rev[:7]}"):
        return path
    sys.exit(f"no cargo checkout of ai-memory at {rev[:7]}: run `make memory` first")


def ftl(path: pathlib.Path) -> dict:
    out = {}
    for line in path.read_text().splitlines():
        if " = " in line and not line.startswith((" ", "#")):
            key, value = line.split(" = ", 1)
            out[key.strip()] = value
    return out


def swift(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    rev = pinned_rev()
    up = checkout(rev)
    source = (up / "crates/ai-memory-web/src/documentation.rs").read_text()
    pattern = re.compile(r'document!\(\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)"(?:,\s*pt "([^"]+)")?\s*\)')
    docs = pattern.findall(source)
    if not docs:
        sys.exit("no document! entries found")
    english = ftl(up / "crates/ai-memory-core/locales/en/diagnostics.ftl")
    portuguese = ftl(up / "crates/ai-memory-core/locales/pt-BR/diagnostics.ftl")
    by_text = {value: key for key, value in english.items()}

    def pt(text: str) -> str:
        key = by_text.get(text)
        return portuguese.get(key, text) if key else text

    lines = [
        "import Foundation",
        "import Strings",
        "",
        "// Generated by tools/memory_panel_guides.py from ai-memory-web's documentation catalog and",
        f"// ai-memory-core's diagnostics.ftl at {rev[:7]} (plan 40 G). Do not edit by hand.",
        "",
        "/// One of upstream's guides: what the Documentação screen lists; a click opens it on GitHub, at the",
        "/// pinned commit (the guides stay out of the engine, plan 40 B).",
        "public struct PanelGuide: Equatable, Sendable {",
        "    public let id: String",
        "    let titleEN: String, titlePT: String",
        "    let summaryEN: String, summaryPT: String",
        "    let categoryEN: String, categoryPT: String",
        "    let source: String",
        "    let sourcePT: String?",
        "",
        "    public var title: String { T(titleEN, titlePT) }",
        "    public var summary: String { T(summaryEN, summaryPT) }",
        "    public var category: String { T(categoryEN, categoryPT) }",
        "    /// The guide on GitHub at the pinned commit, in Portuguese when upstream has it.",
        f'    public var url: URL {{ URL(string: "{REPO}/blob/{rev}/" + (Strings.language == .pt ? sourcePT ?? source : source))! }}',
        "    /// Release history (the changelogs), the section Histórico de alterações.",
        '    public var isChangelog: Bool { categoryEN == "Release history" }',
        "",
        f'    public static let version = "{rev[:7]}"',
        "    public static let all: [PanelGuide] = [",
    ]
    for gid, title, desc, cat, src, pt_src in docs:
        lines.append(
            f"        PanelGuide(id: {swift(gid)}, titleEN: {swift(title)}, titlePT: {swift(pt(title))}, "
            f"summaryEN: {swift(desc)}, summaryPT: {swift(pt(desc))},"
        )
        lines.append(
            f"                   categoryEN: {swift(cat)}, categoryPT: {swift(pt(cat))}, source: {swift(src)}, "
            f"sourcePT: {swift(pt_src) if pt_src else 'nil'}),"
        )
    lines += ["    ]", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(docs)} guides")


if __name__ == "__main__":
    main()
